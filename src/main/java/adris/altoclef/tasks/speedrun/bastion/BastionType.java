package adris.altoclef.tasks.speedrun.bastion;

/**
 * The four bastion remnant types in 1.16+.
 * Ordered roughly by speedrun value for pearl/gold runs.
 */
public enum BastionType {
    TREASURE,   // Best – clean gold + chests
    HOUSING,    // Good gold, more piglins
    BRIDGE,     // High risk / reward
    STABLES,    // Usually least valuable for pure pearl routes
    UNKNOWN
}
